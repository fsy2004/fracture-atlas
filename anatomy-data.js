function spineOrRib(key){
 const [ordinal,region]=key.split(' '),n=order.indexOf(ordinal)+1;
 if(key.endsWith('cervical vertebra'))return n===7?entry('隆椎常作为体表计数标志。',
  ['长棘突','后方棘突明显，通常不分叉。'],['横突孔','孔可较小，椎动脉多数在更高节的横突孔进入。']):cervical;
 if(key.endsWith('thoracic vertebra')){
  if(n>=11)return entry('胸腰段过渡，肋头常接椎体侧面的完整关节面。',
   ['椎体肋凹','接同序数肋头。'],['横突','通常缺少典型的横突肋凹。'],['关节突','第十二胸椎下关节面逐渐呈腰椎样方向。']);
  if(n===1)return entry('第一胸椎位于颈胸交界。',
   ['第一肋完整肋凹','椎体侧面上部与第一肋头对合。'],['下部肋凹','可参与接纳第二肋头。'],['横突肋凹','同侧第一肋结节在此与横突相接。']);
  return thoracic;
 }
 if(key.endsWith('lumbar vertebra'))return n===5?entry('第五腰椎直接与骶骨相接，腰骶交界负荷较大。',
  ['楔形椎体','椎体常前高后低，下终板朝向骶骨。'],['横突和下关节突','粗壮横突向两侧延伸，下关节突与骶骨上关节突对合。']):lumbar;
 if(region!=='rib')return null;
 if(n>=11)return floatingRib;
 if(n===1)return entry('第一肋最短而扁平，位于胸廓上口。',
  ['斜角肌结节','位于上面，将锁骨下静脉沟和动脉沟分开。'],
  ['肋头和结节','靠近第一胸椎。'],['前端','与第一肋软骨相接，向胸骨柄延续。']);
 if(n===2)return entry('第二肋长于第一肋，前端是胸骨角的计数标志。',
  ['前锯肌粗隆','位于肋体上面，是区分第二肋的形态标志。'],
  ['肋头与结节','后端与胸椎构成关节。'],['前端','第二肋软骨于胸骨角附近与胸骨连接。']);
 if(n===10)return entry('第十肋为下位肋骨，前端经肋软骨参与肋弓，存在个体变异。',
  ['肋头','后端常只有一个主要肋头关节面。'],['肋结节和肋沟','后部辨认肋结节，向外沿内下缘找肋沟。']);
 return typicalRib;
}
function handOrFoot(key){
 const metatarsal=key.endsWith('metatarsal bone'),metacarpal=key.endsWith('metacarpal bone');
 if(metatarsal||metacarpal){
  const n=order.indexOf(key.split(' ')[0])+1;
  const proximal=metatarsal?(n===5?'基底外侧有第五跖骨粗隆，邻接腓骨短肌腱。':n===2?'基底嵌入楔骨间，与中间楔骨的对线用于辨认跗跖关节。':n===1?'基底与内侧楔骨相接。':'近侧与跗骨形成跗跖关节。'):
    (n===1?'第一掌骨基底与大多角骨形成鞍状关节。':n===3?'第三掌骨基底背侧可见茎突。':'基底与远排腕骨相接。');
  return entry(metatarsal?'从跗骨向趾骨依次辨认基底、骨干及骨头。':'从腕向手指依次辨认基底、骨干及骨头。',
   ['基底',proximal],['骨干与骨颈','沿长轴观察骨干和头下方的收窄区。'],
   ['骨头',metatarsal&&n===1?'与拇趾近节相对，跖面与两枚籽骨相邻。':'远端圆钝，与近节骨基底对合。']);
 }
 const m=key.match(/^(proximal|middle|distal) phalanx.*(toe|finger|thumb)$/);
 if(!m)return null;
 const part=m[1],foot=m[2]==='toe';
 return entry((foot?'趾骨':'指骨')+'由基底、骨体和远端构成。',
  ['基底',part==='proximal'?'凹形关节面与'+(foot?'跖':'掌')+'骨头相对。':'近侧与上一节指趾骨滑车对合。'],
  ['骨体','掌侧或跖侧为屈肌腱行走方向，背侧邻伸肌腱。'],
  [part==='distal'?'末端粗隆':'头与滑车',part==='distal'?'末段扩展并支撑指趾尖。':'两侧关节面在远端构成滑车，与下一个指趾节相接。']);
}
export function anatomyFor(name){
 const key=normalized(name);
 return D[key]||spineOrRib(key)||handOrFoot(key);
}
