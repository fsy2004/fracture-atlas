export function fractureNote(course,index){
 const entry=references[course?.family||course?.id];
 const variant=course?.variants?.[index];
 const points=entry?.notes?.[variant?.name];
 if(!Array.isArray(points)) return null;
 const qualifier=course.family?'（同类部位）':course.id==='plateau'&&variant.depression?'（压陷形态为补充示例）':'';
 return {points:[...points],locator:entry.locator+qualifier};
}
