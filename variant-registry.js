export function canonicalCourse(course){
 const index=registry[course.id];
 if(!index)throw Error('Missing variant registry entry for '+course.id);
 const byLabel=new Map(course.variants.map(variant=>[variant.name,variant]));
 const variants=Object.entries(index).map(([id,label])=>{
  const original=byLabel.get(label);
  if(!original)throw Error('Unmatched variant '+course.id+'/'+id+' '+label);
  return {...original,id};
 });
 if(byLabel.size!==variants.length||variants.length!==course.variants.length)throw Error('Registry size mismatch for '+course.id);
 return {...course,variants};
}
export function variantIndex(course,selector){
 const index=course.variants.findIndex(variant=>variant.id===selector);
 if(index>=0)return index;
 const legacy=/^\d+$/.test(selector||'')?Number(selector):0;
 return Math.min(course.variants.length-1,legacy);
}
